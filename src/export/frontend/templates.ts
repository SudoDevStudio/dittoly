import type { AppBundle, Framework } from '../bundle.js';
import { themeCss } from '../theme.js';
import type { TarFile } from '../tar.js';
import { ANGULAR_FILES } from './angular.js';
import { CORE_DTS, CORE_JS } from './core.js';
import { REACT_APP_TSX } from './react.js';
import { RENDER_JS } from './render.js';
import { APP_CSS } from './styles.js';
import { VUE_FILES } from './vue.js';

/**
 * The frontend project of an export, per framework. The components are fixed and tested; what
 * changes per app is data: the page plan, the theme (theme.css) and the app's name. Versions
 * are pinned to releases at least two weeks old when this template was written, and every
 * project uses TypeScript 6.0 (Angular 22 requires it).
 */

const V = {
  react: '19.3.0',
  typesReact: '19.3.0',
  vite: '8.3.2',
  pluginReact: '6.1.1',
  next: '16.3.8',
  angular: '22.2.1',
  rxjs: '7.8.2',
  zone: '0.16.3',
  astro: '7.3.5',
  vue: '3.5.43',
  pluginVue: '6.0.9',
  vueTsc: '3.3.12',
  typescript: '6.0.3',
};

/** Where `npm run build` puts the static site, per framework (copied into the image). */
export const FRONTEND_OUT: Record<Framework, string> = { react: 'dist', vue: 'dist', astro: 'dist', next: 'out', angular: 'dist/app/browser' };

const json = (v: unknown) => JSON.stringify(v, null, 2) + '\n';
const pkg = (b: AppBundle, scripts: Record<string, string>, deps: Record<string, string>, dev: Record<string, string>) =>
  json({ name: `${b.slug}-frontend`, private: true, version: '1.0.0', type: 'module', scripts, dependencies: deps, devDependencies: dev });

const escHtml = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);
const icon = (b: AppBundle) => (b.theme?.brand.logo ? `<link rel="icon" href="${escHtml(b.theme.brand.logo)}" />` : '');

function readme(b: AppBundle, f: Framework, dev: string): string {
  const name = { react: 'React (Vite)', next: 'Next.js (static export)', angular: 'Angular', astro: 'Astro', vue: 'Vue (Vite)' }[f];
  return `# ${b.name}: frontend (${name})

Generated by Dittoly. The Docker build compiles it and the app serves it, so you only need this folder to change the look.

- \`src/app.config.json\` (or \`app.config.json\`): the page plan (pages, what each shows, which Flow it runs) and the app name.
- \`theme.css\`: brand colours, font and corners (light and dark). \`app.css\`: the shared component styles.
- \`dittoly/core.js\`: the API client and helpers (\`core.d.ts\` has the types). It talks to the app's API at the same address.

Local development, with the app running on port 8080:

\`\`\`sh
npm install
${dev}
\`\`\`
`;
}

function shared(b: AppBundle, dir: string): TarFile[] {
  return [
    { path: `${dir}/dittoly/core.js`, content: CORE_JS },
    { path: `${dir}/dittoly/core.d.ts`, content: CORE_DTS },
    { path: `${dir}/theme.css`, content: themeCss(b.theme!) },
    { path: `${dir}/app.css`, content: APP_CSS },
  ];
}

const config = (b: AppBundle) => json({ name: b.name, plan: b.frontend!.plan });

function react(b: AppBundle): TarFile[] {
  return [
    { path: 'package.json', content: pkg(b, { dev: 'vite', build: 'vite build', typecheck: 'tsc --noEmit' }, { react: V.react, 'react-dom': V.react }, { vite: V.vite, '@vitejs/plugin-react': V.pluginReact, typescript: V.typescript, '@types/react': V.typesReact, '@types/react-dom': V.typesReact }) },
    { path: 'vite.config.ts', content: `import { defineConfig } from 'vite';\nimport react from '@vitejs/plugin-react';\n\n// In development the API is the app on port 8080 (or VITE_API_PROXY).\nexport default defineConfig({\n  plugins: [react()],\n  server: { proxy: { '/api': process.env.VITE_API_PROXY ?? 'http://localhost:8080' } },\n});\n` },
    { path: 'tsconfig.json', content: json({ compilerOptions: { target: 'ES2022', lib: ['ES2022', 'DOM', 'DOM.Iterable'], module: 'ESNext', moduleResolution: 'bundler', jsx: 'react-jsx', strict: true, noEmit: true, skipLibCheck: true, allowJs: false, types: ['vite/client'] }, include: ['src'] }) },
    { path: 'index.html', content: `<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="utf-8" />\n    <meta name="viewport" content="width=device-width, initial-scale=1" />\n    <title>${escHtml(b.name)}</title>\n    ${icon(b)}\n  </head>\n  <body>\n    <div id="root"></div>\n    <script type="module" src="/src/main.tsx"></script>\n  </body>\n</html>\n` },
    { path: 'src/main.tsx', content: `import { StrictMode } from 'react';\nimport { createRoot } from 'react-dom/client';\nimport App from './App';\nimport './theme.css';\nimport './app.css';\n\ncreateRoot(document.getElementById('root')!).render(<StrictMode><App /></StrictMode>);\n` },
    { path: 'src/App.tsx', content: REACT_APP_TSX },
    { path: 'src/app.config.json', content: config(b) },
    ...shared(b, 'src'),
    { path: 'README.md', content: readme(b, 'react', 'npm run dev    # http://localhost:5173') },
  ];
}

function next(b: AppBundle): TarFile[] {
  return [
    { path: 'package.json', content: pkg(b, { dev: 'next dev', build: 'next build' }, { next: V.next, react: V.react, 'react-dom': V.react }, { typescript: V.typescript, '@types/react': V.typesReact, '@types/react-dom': V.typesReact, '@types/node': '24.19.2' }) },
    { path: 'next.config.mjs', content: `/** Static export: the app serves the files in out/. */\nexport default {\n  output: 'export',\n  trailingSlash: true,\n  images: { unoptimized: true },\n};\n` },
    { path: 'tsconfig.json', content: json({ compilerOptions: { target: 'ES2022', lib: ['ES2022', 'DOM', 'DOM.Iterable'], module: 'ESNext', moduleResolution: 'bundler', jsx: 'react-jsx', strict: true, noEmit: true, skipLibCheck: true, allowJs: false, resolveJsonModule: true, isolatedModules: true, incremental: true, esModuleInterop: true, plugins: [{ name: 'next' }] }, include: ['next-env.d.ts', '**/*.ts', '**/*.tsx', '.next/types/**/*.ts', '.next/dev/types/**/*.ts'], exclude: ['node_modules'] }) },
    { path: 'app/layout.tsx', content: `import type { Metadata } from 'next';\nimport type { ReactNode } from 'react';\nimport config from './app.config.json';\nimport './theme.css';\nimport './app.css';\n\nexport const metadata: Metadata = { title: config.name };\n\nexport default function RootLayout({ children }: { children: ReactNode }) {\n  return (\n    <html lang="en">\n      <body>{children}</body>\n    </html>\n  );\n}\n` },
    { path: 'app/[[...slug]]/page.tsx', content: `import App from '../App';\nimport config from '../app.config.json';\n\n// One static page per path in the plan; the app itself runs in the browser.\nexport const dynamicParams = false;\nexport function generateStaticParams() {\n  return [{ slug: [] as string[] }, ...config.plan.pages.filter((p) => p.path !== '/').map((p) => ({ slug: p.path.slice(1).split('/') }))];\n}\n\nexport default function Page() {\n  return <App />;\n}\n` },
    { path: 'app/App.tsx', content: `'use client';\n${REACT_APP_TSX}` },
    { path: 'app/app.config.json', content: config(b) },
    ...shared(b, 'app'),
    { path: 'README.md', content: readme(b, 'next', 'npm run dev    # http://localhost:3000 (start the app with CORS_ORIGINS=http://localhost:3000)') },
  ];
}

