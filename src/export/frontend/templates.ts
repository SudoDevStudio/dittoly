function astro(b: AppBundle): TarFile[] {
  return [
    { path: 'package.json', content: pkg(b, { dev: 'astro dev', build: 'astro build' }, { astro: V.astro }, { typescript: V.typescript }) },
    { path: 'astro.config.mjs', content: `import { defineConfig } from 'astro/config';\n\n// Static pages; in development the API is the app on port 8080.\nexport default defineConfig({\n  output: 'static',\n  vite: { server: { proxy: { '/api': 'http://localhost:8080' } } },\n});\n` },
    { path: 'tsconfig.json', content: json({ extends: 'astro/tsconfigs/strict', include: ['.astro/types.d.ts', '**/*'], exclude: ['dist'] }) },
    {
      path: 'src/pages/[...slug].astro',
      content: `---
import config from '../app.config.json';
import '../theme.css';
import '../app.css';

// One static page per path in the plan; the pages render in the browser from the app's API.
export function getStaticPaths() {
  return [{ params: { slug: undefined } }, ...config.plan.pages.filter((p) => p.path !== '/').map((p) => ({ params: { slug: p.path.slice(1) } }))];
}
---
<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>{config.name}</title>
    ${icon(b)}
  </head>
  <body>
    <div id="root"><p class="dty-main dty-muted">Loading…</p></div>
    <script>
      import { mount } from '../dittoly/render.js';
      mount(document.getElementById('root'));
    </script>
  </body>
</html>
`,
    },
    { path: 'src/dittoly/render.js', content: RENDER_JS },
    { path: 'src/app.config.json', content: config(b) },
    ...shared(b, 'src'),
    { path: 'README.md', content: readme(b, 'astro', 'npm run dev    # http://localhost:4321') },
  ];
}

/** The frontend project for the bundle's framework (empty when it has none). */
export function frontendFiles(b: AppBundle): TarFile[] {
  if (!b.frontend || !b.theme) return [];
  return { react, next, vue, angular, astro }[b.frontend.framework](b);
}
