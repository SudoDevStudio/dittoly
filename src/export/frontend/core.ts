/**
 * The browser-side core every exported frontend uses (the built-in UI and each framework
 * template): the API client, form fields from a Flow's input schema, and how results are
 * found and shown. It is plain JavaScript with a declaration file, so React, Next, Vue,
 * Angular and Astro projects all import the same code.
 */

